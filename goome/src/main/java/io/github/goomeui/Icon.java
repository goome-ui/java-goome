package io.github.goomeui;

/** The built in icons the ui draws, each can be swapped for your own bitmap with Theme.icon() or Ui.pushIcon(). */
public enum Icon {
    /** The arrow down icon. */
    ARROW_DOWN,
    /** The arrow right icon. */
    ARROW_RIGHT,
    /** The arrow up icon. */
    ARROW_UP,
    /** The arrow left icon. */
    ARROW_LEFT,
    /** The check mark in checkboxes. */
    CHECK,
    /** The dot in a selected radio button. */
    RADIO_DOT,
    /** The close button cross. */
    CLOSE,
    /** The minimize button. */
    MINIMIZE,
    /** The maximize button. */
    MAXIMIZE,
    /** The restore button. */
    RESTORE,
    /** The window resize grip. */
    RESIZE,
    /** The arrow for sorting up. */
    SORT_UP,
    /** The arrow for sorting down. */
    SORT_DOWN,
    /** The plus sign. */
    PLUS,
    /** The minus sign. */
    MINUS,
    /** The slider knob. */
    SLIDER_KNOB,
    /** The toggle knob. */
    TOGGLE_KNOB,
    /** The collapse icon. */
    COLLAPSE,
    /** The expand icon. */
    EXPAND,
    /** The drag handle. */
    DRAG_HANDLE,
    /** The toast icon. */
    TOAST,
    /** The color picker icon. */
    PICKER;

    /** How many icons there are. */
    public static final int COUNT = 22;
}
